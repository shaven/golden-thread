def _readme(vault, slug):
    return os.path.join(vault, "Projects", slug, "README.md")


def _frontmatter(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
    except OSError:
        return None
    m = re.match(r"^---\s*\n(.*?)\n---", text, re.S)
    if not m:
        return None
    return dict(re.findall(r"^([a-z_]+):\s*(.*)$", m.group(1), re.M))


def projects_missing_flag(vault):
    out = []
    base = os.path.join(vault, "Projects")
    for readme in sorted(glob.glob(os.path.join(base, "*", "README.md")) +
                         glob.glob(os.path.join(base, "*", "*", "README.md"))):
        proj = os.path.dirname(readme)
        if not os.path.exists(os.path.join(proj, "idea.md")):
            continue
        fm = _frontmatter(readme)
        if fm is None or "release_pipeline" in fm:
            continue
        out.append(os.path.relpath(proj, base).replace(os.sep, "/"))
    return out


def queue_flag(vault, rel_project, value, dry_run=False):
    cmd = [sys.executable or "python3", os.path.join(HERE, "gt_write_queue.py"),
           "--vault", vault, "--path", "Projects/%s/README.md" % rel_project,
           "--op", "set-property", "--key", "release_pipeline", "--value", value,
           "--hint", "gt_pipeline: release_pipeline flag"]
    if dry_run:
        cmd.append("--dry-run")
    p = subprocess.run(cmd, capture_output=True, text=True)
    return p.returncode, (p.stdout + p.stderr).strip()


def cmd_flag(vault, project=None, value=None, all_missing=False, dry_run=False, drain=True):
    vault = os.path.abspath(os.path.expanduser(vault))
    if all_missing:
        todo = [(p, "planned") for p in projects_missing_flag(vault)]
    else:
        if value not in VALUES:
            print("REFUSED: --value must be one of %s" % ", ".join(VALUES))
            return 2
        if not os.path.isfile(_readme(vault, project)):
            print("REFUSED: no project README at Projects/%s/README.md" % project)
            return 2
        todo = [(project, value)]
    bad = 0
    for rel, val in todo:
        rc, out = queue_flag(vault, rel, val, dry_run)
        print("%s release_pipeline: %s  Projects/%s/README.md%s"
              % ("would queue" if dry_run else ("queued" if rc == 0 else "REFUSED"), val, rel,
                 "" if rc == 0 else "  (%s)" % out[-200:]))
        bad += rc != 0
    if not todo:
        print("every project README already carries release_pipeline")
    if todo and drain and not dry_run:
        p = subprocess.run([sys.executable or "python3", os.path.join(HERE, "gt_broker.py"),
                            "drain", "--vault", vault], capture_output=True, text=True)
        print((p.stdout or p.stderr).strip().splitlines()[-1:] and
              (p.stdout or p.stderr).strip().splitlines()[-1] or "drained")
    return 1 if bad else 0


# --------------------------------------------------------------------- CLI ----

def main(argv=None):
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--repo", default=".", help="the project's code root (default: here)")
    common.add_argument("--dry-run", action="store_true", default=argparse.SUPPRESS,
                        help="say what would change; write nothing")
    common.add_argument("--vault", default=argparse.SUPPRESS,
                        help="the vault (only `flag` writes one)")
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0], parents=[common])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("init", parents=[common], help="adopt the pipeline (never overwrites)")
    p.add_argument("--project", help="the vault project slug, recorded in the steps file")
    sub.add_parser("list", parents=[common], help="the steps in run order")
    sub.add_parser("check", parents=[common], help="validate order, commands, release.sh")
    p = sub.add_parser("add", parents=[common], help="insert a step or gate")
    p.add_argument("id")
    p.add_argument("--cmd", dest="cmdline", required=True)
    p.add_argument("--kind", choices=("step", "gate"), default="step")
    p.add_argument("--after", help="the step it must follow (default: the last step)")
    p.add_argument("--guarantee", default="", help="one line: what passing it guarantees")
    p.add_argument("--optional", action="store_true", help="a failure is reported, not fatal")
    p = sub.add_parser("set", parents=[common], help="change one step's command")
    p.add_argument("id")
    p.add_argument("--cmd", dest="cmdline", required=True)
    p = sub.add_parser("remove", parents=[common], help="remove a step (a default needs --reason)")
    p.add_argument("id")
    p.add_argument("--reason")
    sub.add_parser("render", parents=[common], help="regenerate release.sh from the steps file")
    p = sub.add_parser("run", parents=[common], help="run release.sh")
    p.add_argument("--until")
    p.add_argument("--from", dest="frm")
    p.add_argument("--go", action="store_true", help="the owner's explicit go-ahead")
    p.add_argument("--inside", choices=("allin",), help=argparse.SUPPRESS)
    p = sub.add_parser("builtin", parents=[common], help="run one default step")
    p.add_argument("name", choices=gt_recipe.BUILTINS)
    p = sub.add_parser("flag", parents=[common],
                       help="set release_pipeline on a project README (through the write queue)")
    p.add_argument("--project")
    p.add_argument("--value", choices=VALUES)
    p.add_argument("--all-missing", action="store_true",
                   help="record `planned` on every project README without the flag")
    a = ap.parse_args(argv)
    dry = getattr(a, "dry_run", False)

    if a.cmd == "flag":
        vault = getattr(a, "vault", None)
        if not vault:
            print("REFUSED: flag writes the vault, so --vault is required (never inferred)")
            return 2
        if not a.all_missing and not (a.project and a.value):
            print("REFUSED: give --project and --value, or --all-missing")
            return 2
        return cmd_flag(vault, a.project, a.value, a.all_missing, dry)

    repo = repo_root(os.path.abspath(os.path.expanduser(a.repo)))
    if a.cmd == "builtin":
        return builtin(a.name, repo)
    if a.cmd == "init":
        return cmd_init(repo, a.project, dry)
    if a.cmd == "check":
        return cmd_check(repo)
    try:
        if a.cmd == "list":
            return cmd_list(repo)
        if a.cmd == "add":
            return cmd_add(repo, a.id, a.cmdline, a.kind, a.after, a.guarantee, a.optional, dry)
        if a.cmd == "set":
            return cmd_set(repo, a.id, a.cmdline, dry)
        if a.cmd == "remove":
            return cmd_remove(repo, a.id, a.reason, dry)
        if a.cmd == "render":
            return cmd_render(repo, dry)
        if a.cmd == "run":
            return cmd_run(repo, a.until, a.frm, a.go, dry, a.inside)
    except OSError:
        print("no %s in %s -- adopt it with: gt_pipeline.py init --repo %s"
              % (STEPS_FILE, repo, repo))
        return 2
    except gt_recipe.RecipeError as exc:
        print("%s is invalid: %s" % (STEPS_FILE, exc))
        return 2
    return 2


if __name__ == "__main__":
    sys.exit(main())
